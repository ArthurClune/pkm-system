# pattern: Imperative Shell
"""Dump the tag-name word class, so the server and the web read a hashtag's
name by one frozen table rather than by each runtime's Unicode tables:
uv run python -m pkm.tag_chars_dump --table > src/pkm/contracts/tag_chars.py
uv run python -m pkm.tag_chars_dump > ../web/src/grammar/tagChars.gen.ts
`--table` reads the running interpreter's `\\w` and is run only to move the
table to a new Unicode version on purpose; the plain run writes the
committed table as a TS string. Every bound is written as an escape, so no
editor can swap a character. Guarded by tests/test_tag_chars_artifact.py
(same pattern as title_whitespace_dump)."""
from __future__ import annotations

import argparse
import re
import sys
import unicodedata

TS_HEADER = (
    "// GENERATED by `uv run python -m pkm.tag_chars_dump` (server/src/pkm/"
    "tag_chars_dump.py).\n// Do not edit; regenerate when contracts/"
    "tag_chars.py TAG_WORD_RANGES changes (server test enforces).\n")

_PY_HEADER = '''\
# pattern: Functional Core
"""The code points a tag name's word characters may be: CPython's `\\\\w`
under Unicode {version}, frozen as inclusive ranges so the server (refs.py)
and the web (grammar/tagChars.gen.ts) read one class whatever Unicode
tables their runtimes carry.

GENERATED by `uv run python -m pkm.tag_chars_dump --table`
(server/src/pkm/tag_chars_dump.py). Do not edit by hand."""

TAG_CHARS_UNICODE_VERSION: str = "{version}"

TAG_WORD_RANGES: tuple[tuple[int, int], ...] = (
'''

_RANGES_PER_LINE = 5  # astral bounds keep a line of five within 120
_SURROGATES = range(0xD800, 0xE000)
_WORD = re.compile(r"\w")


def word_ranges() -> list[tuple[int, int]]:
    """The running interpreter's `\\w` as inclusive, ascending ranges."""
    ranges: list[tuple[int, int]] = []
    for cp in range(sys.maxunicode + 1):
        if cp in _SURROGATES or _WORD.fullmatch(chr(cp)) is None:
            continue
        if ranges and ranges[-1][1] == cp - 1:
            ranges[-1] = (ranges[-1][0], cp)
        else:
            ranges.append((cp, cp))
    return ranges


def python_module(ranges: list[tuple[int, int]] | tuple[tuple[int, int], ...],
                  unicode_version: str) -> str:
    lines = [
        "    " + " ".join(f"(0x{lo:04X}, 0x{hi:04X}),"
                          for lo, hi in ranges[i:i + _RANGES_PER_LINE])
        for i in range(0, len(ranges), _RANGES_PER_LINE)
    ]
    body = "".join(f"{line}\n" for line in lines)
    return _PY_HEADER.format(version=unicode_version) + body + ")\n"


def ts_module(ranges: list[tuple[int, int]] | tuple[tuple[int, int], ...]
              ) -> str:
    # `\\u{hex}` in the TS string reaches the RegExp as `\u{hex}`, which a
    # "u"-flagged class reads as that code point.
    def bound(cp: int) -> str:
        return f"\\\\u{{{cp:x}}}"
    parts = "".join(bound(lo) if lo == hi else f"{bound(lo)}-{bound(hi)}"
                    for lo, hi in ranges)
    return f'{TS_HEADER}export const TAG_WORD_CLASS = "{parts}";\n'


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="pkm.tag_chars_dump")
    parser.add_argument(
        "--table", action="store_true",
        help="print contracts/tag_chars.py from this interpreter's \\w")
    args = parser.parse_args(argv)
    if args.table:
        print(python_module(word_ranges(), unicodedata.unidata_version),
              end="")
        return 0
    # Imported here, not at the top: `--table > contracts/tag_chars.py`
    # empties that file before this runs, so a top-level import would fail.
    from pkm.contracts.tag_chars import TAG_WORD_RANGES
    print(ts_module(TAG_WORD_RANGES), end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
