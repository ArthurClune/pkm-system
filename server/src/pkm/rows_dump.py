# pattern: Imperative Shell
"""Dump the row vocabulary and brand registry for the web:
uv run python -m pkm.rows_dump
writes web/src/replica/columns.gen.ts (the `Columns` interface, its
COLUMN_META and the column-key overrides) and
web/tooling/brandRegistry.gen.json (the lint's registry tables). Guarded by
tests/test_rows_artifact.py (same pattern as schema_dump). Generation fails
rather than emit a plain `string` for a brand the web does not define."""
from __future__ import annotations

import json
import re
from pathlib import Path

from pkm import brand_registry as reg
from pkm.rows import KEYS, KeySpec

WEB = Path(__file__).resolve().parents[3] / "web"
COLUMNS_TS = WEB / "src" / "replica" / "columns.gen.ts"
REGISTRY_JSON = WEB / "tooling" / "brandRegistry.gen.json"
BRANDS_TS = WEB / "src" / "api" / "brands.ts"

# Web-only brands a row key may carry: name -> (module it is exported
# from, relative to src/replica, base type).
WEB_ONLY: dict[str, tuple[str, str]] = {
    "PendingRowId": ("./client", "int"),
}

HEADER = (
    "// GENERATED by `uv run python -m pkm.rows_dump` (server/src/pkm/"
    "rows_dump.py).\n// Do not edit; regenerate when rows.py or "
    "brand_registry.py changes (server test enforces).\n")

_TS_BASE = {"str": "string", "int": "number"}
_META_BASE = {"str": "text", "int": "int"}


class RowsDumpError(Exception):
    pass


def _brands_exported() -> set[str]:
    return set(re.findall(r"^export type (\w+) =", BRANDS_TS.read_text(),
                          re.MULTILINE))


class _Key:
    def __init__(self, name: str, ts: str, brand: str | None, base: str,
                 nullable: bool, literals: tuple[object, ...] | None) -> None:
        self.name, self.ts, self.brand = name, ts, brand
        self.base, self.nullable, self.literals = base, nullable, literals


def _server_key(name: str, spec: KeySpec, exported: set[str]) -> _Key:
    base = _META_BASE[spec.base.__name__]
    if spec.literals is not None:
        if spec.brand is not None:
            raise RowsDumpError(
                f"{name}: literals and brand {spec.brand} are exclusive")
        ts = " | ".join(json.dumps(v) for v in spec.literals)
    elif spec.brand is not None:
        if spec.brand not in exported:
            raise RowsDumpError(
                f"{name}: brand {spec.brand} has no export in brands.ts")
        ts = spec.brand
    else:
        ts = _TS_BASE[spec.base.__name__]
    return _Key(name, ts, spec.brand, base, spec.nullable, spec.literals)


def _client_key(name: str, type_name: str, nullable: bool,
                exported: set[str]) -> _Key:
    if type_name in ("string", "number"):
        base = "text" if type_name == "string" else "int"
        return _Key(name, type_name, None, base, nullable, None)
    if type_name in WEB_ONLY:
        return _Key(name, type_name, type_name, WEB_ONLY[type_name][1],
                    nullable, None)
    if type_name in reg.SHAPES and type_name in exported:
        return _Key(name, type_name, type_name, reg.SHAPES[type_name][0],
                    nullable, None)
    raise RowsDumpError(
        f"{name}: client key type {type_name} is neither a primitive, a "
        f"server brand exported from brands.ts, nor in rows_dump.WEB_ONLY")


def _all_keys() -> list[_Key]:
    exported = _brands_exported()
    overlap = set(KEYS) & set(reg.CLIENT_KEYS)
    if overlap:
        raise RowsDumpError(f"keys in both Row and CLIENT_KEYS: {overlap}")
    keys = [_server_key(n, s, exported) for n, s in KEYS.items()]
    keys += [_client_key(n, t, nullable, exported)
             for n, (t, nullable) in reg.CLIENT_KEYS.items()]
    return keys


def _imports(keys: list[_Key]) -> list[str]:
    shared = sorted({k.brand for k in keys
                     if k.brand and k.brand not in WEB_ONLY
                     and k.literals is None})
    lines = []
    if shared:
        lines.append(f'import type {{ {", ".join(shared)} }} '
                     'from "../api/brands";')
    for brand in sorted(WEB_ONLY):
        if any(k.brand == brand for k in keys):
            lines.append(f'import type {{ {brand} }} '
                         f'from "{WEB_ONLY[brand][0]}";')
    return lines


def columns_module() -> str:
    keys = _all_keys()
    out = [HEADER, *_imports(keys), "",
           "/** Every key a database row may carry, with its type. */",
           "export interface Columns {"]
    for k in keys:
        null = " | null" if k.nullable else ""
        out.append(f"  {k.name}: {k.ts}{null};")
    out += ["}", "",
            "export interface ColumnMeta {",
            "  readonly brand: string | null;",
            '  readonly base: "text" | "int" | "real" | "blob";',
            "  readonly nullable: boolean;",
            "  /** The allowed values of a literal-typed key, else null. */",
            "  readonly literals: readonly (string | number)[] | null;",
            "}", "",
            "export const COLUMN_META: "
            "{ readonly [K in keyof Columns]: ColumnMeta } = {"]
    for k in keys:
        lits = ("null" if k.literals is None else
                "[" + ", ".join(json.dumps(v) for v in k.literals) + "]")
        brand = "null" if k.brand is None else json.dumps(k.brand)
        out.append(
            f'  {k.name}: {{ brand: {brand}, base: "{k.base}", '
            f"nullable: {json.dumps(k.nullable)}, literals: {lits} }},")
    out += ["};", "",
            "/** Table -> {column: key} for columns whose key is not their",
            " * own name. */",
            "export const COLUMN_KEYS: "
            "{ readonly [table: string]: { readonly [column: string]: "
            "keyof Columns } } = "
            + json.dumps(reg.COLUMN_KEYS, indent=2) + ";", "",
            "/** Brand -> base type and the shape its values must fully "
            "match. */",
            "export const BRAND_SHAPES: { readonly [brand: string]: "
            "{ readonly base: string; readonly pattern: string | null } } = "
            + json.dumps({b: {"base": base, "pattern": pat}
                          for b, (base, pat) in reg.SHAPES.items()},
                         indent=2) + ";", ""]
    return "\n".join(out)


def _camel(name: str) -> str:
    return re.sub(r"_([a-z0-9])", lambda m: m.group(1).upper(), name)


def registry_json() -> str:
    names: dict[str, list[str]] = {}
    for name, brands in reg.NAMES.items():
        names[name] = list(brands)
        names.setdefault(_camel(name), list(brands))
    doc = {
        "names": names,
        "mintSites": {b: list(s) for b, s in reg.MINT_SITES.items()},
        "testSupport": list(reg.TEST_SUPPORT),
        "optOutFiles": list(reg.OPT_OUT_FILES),
    }
    return json.dumps(doc, indent=2) + "\n"


def main() -> int:
    COLUMNS_TS.write_text(columns_module())
    REGISTRY_JSON.write_text(registry_json())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
