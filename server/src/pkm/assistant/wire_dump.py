# pattern: Imperative Shell
"""Dump the assistant's wire contract for the web, one TS artifact per
selector, each written by its own `pkm.regen` step:

uv run python -m pkm.assistant.wire_dump preview-keys
    web/src/assistant/previewKeys.gen.ts: the fields a preview carries, the
    keys each approval-card action may carry, and how many code points the
    current text's excerpt is clipped at, so the web refuses a preview
    field or row the server does not send and an excerpt the server did not
    clip. Keyed by the label the card shows, since that is what the preview
    sends; entries sharing a label (`update block`) merge their keys.
uv run python -m pkm.assistant.wire_dump events
    web/src/assistant/events.gen.ts: the `AssistantEvent` union and
    `EVENT_TYPES`, from events.py's dataclasses and `EVENT_NAMES`, so the
    web cannot parse an event or field the server does not send.

Guarded by tests/test_assistant_wire_artifact.py (same pattern as
schema_dump). Generation fails rather than emit a type it cannot map."""
from __future__ import annotations

import dataclasses
import json
import re
import sys
import types
import typing
from collections.abc import Collection, Mapping, Sequence
from pathlib import Path

from pkm.assistant.events import EVENT_NAMES, AssistantEvent, ConfirmRequest
from pkm.assistant.policy import (CURRENT_TEXT_ENTRIES,
                                  SUBTREE_DELETE_ENTRIES,
                                  WRITE_PREVIEW_FIELDS)
from pkm.assistant.write_preview import CURRENT_EXCERPT_CHARS, WritePreview

BRANDS_TS = (Path(__file__).resolve().parents[4]
             / "web" / "src" / "api" / "brands.ts")

HEADER = (
    "// GENERATED by `uv run python -m pkm.assistant.wire_dump "
    "preview-keys`.\n"
    "// Do not edit; regenerate when assistant/policy.py WRITE_PREVIEW_FIELDS,\n"
    "// CURRENT_TEXT_ENTRIES or SUBTREE_DELETE_ENTRIES, or\n"
    "// assistant/write_preview.py CURRENT_EXCERPT_CHARS or WritePreview,\n"
    "// changes (server test enforces).\n"
    "export const PREVIEW_FIELDS: readonly string[] = {preview_fields};\n"
    "export const CURRENT_EXCERPT_CHARS = {excerpt_chars};\n"
    "export type PreviewKeys = { targets: readonly string[];\n"
    "  content: readonly string[]; current: boolean; descendants: boolean };\n"
    "export const PREVIEW_KEYS: ReadonlyMap<string, PreviewKeys> = new Map([\n")


def _strings(keys: list[str]) -> str:
    return "[" + ", ".join(json.dumps(k) for k in keys) + "]"


def ts_module(fields: Mapping[str, tuple[str, tuple[str, ...],
                                         tuple[str, ...]]],
              current_entries: frozenset[str],
              subtree_entries: frozenset[str], excerpt_chars: int,
              preview_fields: Sequence[str]) -> str:
    """The preview's fields, then one entry per label, with the union of
    its entries' keys. Entries
    sharing a label must agree on whether the card shows the current block
    and counts the blocks under it: the web can tell them apart only by
    label, so a disagreement raises ValueError."""
    merged: dict[str, tuple[dict[str, None], dict[str, None],
                            tuple[bool, bool]]] = {}
    for entry, (label, targets, content) in fields.items():
        flags = (entry in current_entries, entry in subtree_entries)
        seen = merged.setdefault(label, ({}, {}, flags))
        if seen[2] != flags:
            raise ValueError(
                f"entries labelled {label!r} disagree on current or "
                "descendants")
        seen[0].update(dict.fromkeys(targets))
        seen[1].update(dict.fromkeys(content))
    rows = "".join(
        f"  [{json.dumps(label)}, {{ targets: {_strings(list(t))}, "
        f"content: {_strings(list(c))}, "
        f"current: {json.dumps(current)}, "
        f"descendants: {json.dumps(descendants)} }}],\n"
        for label, (t, c, (current, descendants)) in sorted(merged.items()))
    header = HEADER.replace("{excerpt_chars}", str(excerpt_chars)).replace(
        "{preview_fields}", _strings(list(preview_fields)))
    return header + rows + "]);\n"


class WireDumpError(Exception):
    pass


EVENTS_HEADER = (
    "// GENERATED by `uv run python -m pkm.assistant.wire_dump events`.\n"
    "// Do not edit; regenerate when assistant/events.py changes (server\n"
    "// test enforces).\n")

_PRIMITIVES: dict[object, str] = {str: "string", bool: "boolean",
                                  int: "number",
                                  dict[str, object]: "Record<string, unknown>"}

# A field whose web type is not its server type, with the import it needs.
# The web parses a malformed preview to null rather than drop the event, so
# the card still shows and offers Deny only, never a turn left waiting on a
# confirm the user cannot see.
_OVERRIDES: dict[tuple[type, str], tuple[str, str]] = {
    (ConfirmRequest, "preview"): (
        "WritePreview | null",
        'import type { WritePreview } from "./writePreview";'),
}


def brands_exported(brands_ts: str) -> set[str]:
    """The type names the web's brands module exports."""
    return set(re.findall(r"^export type (\w+) =", brands_ts, re.MULTILINE))


def _ts_type(hint: object, brands: Collection[str], used: set[str],
             where: str) -> str:
    """The TS type of server type `hint`; every brand it names is added to
    `used` for the import line."""
    if typing.get_origin(hint) in (typing.Union, types.UnionType):
        args = typing.get_args(hint)
        rest = [a for a in args if a is not type(None)]
        if len(rest) == 1 and len(args) == 2:
            return f"{_ts_type(rest[0], brands, used, where)} | null"
    elif isinstance(hint, typing.NewType):
        if hint.__name__ not in brands:
            raise WireDumpError(
                f"{where}: brand {hint.__name__} has no export in brands.ts")
        used.add(hint.__name__)
        return hint.__name__
    elif hint in _PRIMITIVES:
        return _PRIMITIVES[hint]
    raise WireDumpError(f"{where}: no TS mapping for {hint!r}")


def _member(cls: type, name: str, brands: Collection[str],
            imports: set[str], used: set[str]) -> str:
    hints = typing.get_type_hints(cls)
    lines = [f"    type: {json.dumps(name)};\n"]
    for f in dataclasses.fields(cls):
        where = f"{cls.__name__}.{f.name}"
        override = _OVERRIDES.get((cls, f.name))
        if override is not None:
            ts, import_line = override
            imports.add(import_line)
        else:
            ts = _ts_type(hints[f.name], brands, used, where)
        defaulted = (f.default is not dataclasses.MISSING
                     or f.default_factory is not dataclasses.MISSING)
        lines.append(f"    {f.name}{'?' if defaulted else ''}: {ts};\n")
    return "  | {\n" + "".join(lines) + "  }\n"


def events_module(names: Mapping[type, str], members: Collection[type],
                  brands: Collection[str]) -> str:
    """The web's `AssistantEvent` union, one member per event in `names`
    order, and `EVENT_TYPES`. A field with a default is optional: the server
    may stop sending it, so the web must already cope with its absence.
    Raises WireDumpError when `names` and the union's `members` differ, and
    for a field type with no TS mapping, including a brand `brands` lacks."""
    unnamed = sorted(c.__name__ for c in set(members) - set(names))
    stray = sorted(c.__name__ for c in set(names) - set(members))
    if unnamed or stray:
        raise WireDumpError(f"events without a wire name: {unnamed}; "
                            f"wire names without an event: {stray}")
    imports: set[str] = set()
    used: set[str] = set()
    body = "".join(_member(cls, name, brands, imports, used)
                   for cls, name in names.items())
    if used:
        imports.add(f"import type {{ {', '.join(sorted(used))} }} "
                    'from "../api/brands";')
    head = EVENTS_HEADER + "".join(f"{line}\n" for line in sorted(imports))
    names_ts = "".join(f"  {json.dumps(n)},\n" for n in names.values())
    return (head + "\nexport type AssistantEvent =\n" + body.rstrip("\n")
            + ";\n\nexport const EVENT_TYPES: ReadonlySet<string> = "
            "new Set([\n" + names_ts + "]);\n")


def _preview_keys() -> str:
    return ts_module(WRITE_PREVIEW_FIELDS, CURRENT_TEXT_ENTRIES,
                     SUBTREE_DELETE_ENTRIES, CURRENT_EXCERPT_CHARS,
                     [f.name for f in dataclasses.fields(WritePreview)])


def _events() -> str:
    return events_module(EVENT_NAMES, typing.get_args(AssistantEvent),
                         brands_exported(BRANDS_TS.read_text()))


_SELECTORS = {"preview-keys": _preview_keys, "events": _events}


def main(argv: Sequence[str]) -> int:
    if len(argv) != 1 or argv[0] not in _SELECTORS:
        print("usage: python -m pkm.assistant.wire_dump "
              f"{{{'|'.join(_SELECTORS)}}}", file=sys.stderr)
        return 2
    print(_SELECTORS[argv[0]](), end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
