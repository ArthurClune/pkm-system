# pattern: Imperative Shell
"""Dump the keys each approval-card action may carry as a TS artifact, so
the web refuses a preview row the server's table does not name:
uv run python -m pkm.assistant.preview_keys_dump \\
    > ../web/src/assistant/previewKeys.gen.ts
Keyed by the label the card shows, since that is what the preview sends;
entries sharing a label (`update block`) merge their keys. Guarded by
tests/test_preview_keys_artifact.py (same pattern as schema_dump)."""
from __future__ import annotations

import json
from collections.abc import Mapping

from pkm.assistant.policy import (CURRENT_TEXT_ENTRIES,
                                  SUBTREE_DELETE_ENTRIES,
                                  WRITE_PREVIEW_FIELDS)

HEADER = (
    "// GENERATED by `uv run python -m pkm.assistant.preview_keys_dump`.\n"
    "// Do not edit; regenerate when assistant/policy.py WRITE_PREVIEW_FIELDS,\n"
    "// CURRENT_TEXT_ENTRIES or SUBTREE_DELETE_ENTRIES changes (server test\n"
    "// enforces).\n"
    "export type PreviewKeys = { targets: readonly string[];\n"
    "  content: readonly string[]; current: boolean; descendants: boolean };\n"
    "export const PREVIEW_KEYS: ReadonlyMap<string, PreviewKeys> = new Map([\n")


def _strings(keys: list[str]) -> str:
    return "[" + ", ".join(json.dumps(k) for k in keys) + "]"


def ts_module(fields: Mapping[str, tuple[str, tuple[str, ...],
                                         tuple[str, ...]]],
              current_entries: frozenset[str],
              subtree_entries: frozenset[str]) -> str:
    """One entry per label, with the union of its entries' keys. Entries
    sharing a label must agree on whether the card shows the current block
    and counts the blocks under it: the web can tell them apart only by
    label, so a disagreement raises ValueError."""
    merged: dict[str, tuple[dict[str, None], dict[str, None],
                            tuple[bool, bool]]] = {}
    for entry, (label, targets, content) in fields.items():
        flags = (entry in current_entries, entry in subtree_entries)
        seen = merged.setdefault(label, ({}, {}, flags))
        if seen[2] != flags:
            raise ValueError(
                f"entries labelled {label!r} disagree on current or "
                "descendants")
        seen[0].update(dict.fromkeys(targets))
        seen[1].update(dict.fromkeys(content))
    rows = "".join(
        f"  [{json.dumps(label)}, {{ targets: {_strings(list(t))}, "
        f"content: {_strings(list(c))}, "
        f"current: {json.dumps(current)}, "
        f"descendants: {json.dumps(descendants)} }}],\n"
        for label, (t, c, (current, descendants)) in sorted(merged.items()))
    return HEADER + rows + "]);\n"


def main() -> int:
    print(ts_module(WRITE_PREVIEW_FIELDS, CURRENT_TEXT_ENTRIES,
                    SUBTREE_DELETE_ENTRIES), end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
